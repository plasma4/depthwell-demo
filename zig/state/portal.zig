//! The portal descent: the animation that carries the player from depth D down into D+1.
//! We define a "descent" as INCREASING the depth and "ascent" as DECREASING.
//! These terms are accurate *visually*, not algorithmically!
//!
//! A descent runs entirely on a frame counter (`memory.game.portal_frame`) advanced by `handleTick()`,
//! never on wall time, so it plays back identically at any frame rate and can be resumed from a save.
//! The committed world stays at D for every frame but the last;
//! D+1 is only ever a preview, generated into a scratch buffer and drawn over D as it fades in.
const std = @import("std");
const dw = @import("../root.zig");

const memory = dw.memory;
const world = dw.world;
const Chunk = memory.Chunk;
const Sprite = dw.Sprite;
const Coordinate = world.Coordinate;
const Vec2f32 = dw.utils.Vec2f32;
const Vec4f32 = dw.utils.Vec4f32;

/// Length of a descent (60 frames becomes 1 second).
pub const TOTAL_FRAMES: u32 = 120;
/// Frames the player takes to be drawn from where they stand into the portal's mouth.
pub const PULL_FRAMES: u32 = 24;

/// Relative zoom the D+1 overlay starts becoming visible at.
/// The preview must be fully generated by the time the zoom reaches this.
pub const OVERLAY_ZOOM: f64 = 1.5;

/// Baseline number of preview chunks generated per frame (increased if camera view is too big).
pub const CHUNKS_PER_FRAME: u32 = 4;

/// Frames the zoom must stay at or below `OVERLAY_ZOOM` for, giving the preview time to fill.
/// Asserted against the actual curve at the start of every descent rather than assumed.
///
/// This is only a floor on how thinly the work can be spread, not a correctness requirement:
/// `chunksPerFrame()` divides the buffer by the real deadline, so a shorter descent simply generates
/// more chunks per frame rather than showing an unfinished overlay.
pub const MIN_FILL_FRAMES: u32 = 30;

/// Half-width of the block window sampled for debris sprites, in blocks (so an 8x8 window).
pub const DEBRIS_RADIUS: i32 = 4;
/// Distinct block types collected from that window to draw from.
const MAX_PALETTE: usize = @intCast(4 * DEBRIS_RADIUS * DEBRIS_RADIUS);

/// How many shards a descent spawns. Each is one block sprite falling in from a ring around the portal.
/// They are drawn from the sampled palette, so a type shows up as many times as it happens to be picked.
const SHARD_COUNT: usize = 2048;

/// Fraction of the descent over which shards keep starting. Runs almost to the end so terrain is still
/// being drawn in as the zoom closes on `ZOOM_FACTOR`, rather than stopping partway.
const SHARD_SPAWN_SPAN: f64 = 0.9;

/// Frames one shard takes to reach the portal once it starts moving.
const SHARD_TRAVEL_MIN: u32 = 14;
const SHARD_TRAVEL_MAX: u32 = 28;

/// Screen-space ring, in viewport pixels, that shards drift in from.
/// Kept in screen space on purpose: it makes them immune to the zoom,
/// so they can keep being "swallowed" the whole way to `ZOOM_FACTOR`,
/// without anything having to be rescaled per frame.
const SHARD_RADIUS_MIN: f32 = 3.0;
const SHARD_RADIUS_MAX: f32 = 80.0;

/// Edge length of a shard in viewport pixels, before its per-shard jitter.
/// About half a block, so the debris reads as rubble rather than as loose terrain.
const SHARD_SIZE: f32 = @as(f32, dw.CHUNK_SIZE) / 2.0;

/// Radians a shard sweeps around the portal over its travel, and how much that sweep tightens (see `drawDebris()`).
/// The tightening is bounded by construction:
/// the divisor bottoms out at `1 - SHARD_SWIRL_TIGHTEN`, so the total sweep cannot run away.
const SHARD_SWIRL: f32 = 0.35;
const SHARD_SWIRL_TIGHTEN: f32 = 0.75;

comptime {
    // At 1.0 the divisor reaches zero and a shard whips through infinite rotation on its last frame.
    if (SHARD_SWIRL_TIGHTEN < 0.0 or SHARD_SWIRL_TIGHTEN >= 1.0)
        @compileError("SHARD_SWIRL_TIGHTEN must stay below 1 to keep the sweep finite.");
}

/// How far a shard is pushed toward the portal's own light as it is swallowed (see `drawDebris()`).
/// `L` multiplies and `C`/`H` shift, so this brightens the sprite and rotates whatever hue it had toward the mouth's,
/// without flattening every material to one color.
const SHARD_GLOW_LIGHT: f32 = 0.55;
const SHARD_GLOW_CHROMA: f32 = 0.16;
const SHARD_GLOW_HUE: f32 = 0.9;

/// Share of the intake ring thrown back out of the portal,
const DESCENT_OUTWARD_RATIO: f32 = 0.58;
const ASCENT_OUTWARD_RATIO: f32 = 1.0 - 0.58;

/// Streams the intake is gathered into, and how far the pattern turns per frame.
/// Chosen together: over a whole descent the arms sweep a bit under two full turns,
/// slow enough to be followed and fast enough never to sit still.
const INTAKE_ARMS: u32 = 5;
const INTAKE_ARM_SPIN: f32 = 0.09;
const INTAKE_ARM_SPREAD: f32 = 0.2;

comptime {
    // Arms that overlap are just a ring again, which is the thing the streams exist to avoid.
    if (INTAKE_ARM_SPREAD * 2.0 >= std.math.tau / @as(f32, INTAKE_ARMS))
        @compileError("Intake arms must stay narrower than the gap between them.");
}

/// Radians per frame of the wave the intake's spawn rate is beaten against, and the share of the
/// rate that survives a trough. The rate works out to a gust roughly every 15 frames,
/// which is slow enough to be felt as a pulse and quick enough to land several before the commit.
const INTAKE_PULSE_RATE: f64 = 0.42;
const INTAKE_PULSE_FLOOR: f64 = 0.35;

comptime {
    // A zero floor empties the mouth on every trough, which reads as the effect stuttering.
    if (INTAKE_PULSE_FLOOR <= 0.0 or INTAKE_PULSE_FLOOR >= 1.0)
        @compileError("INTAKE_PULSE_FLOOR is the share of the rate a trough keeps.");
}

/// Ring extent in world scale (viewport pixels at 1x zoom), multiplied by the live zoom at spawn.
/// The inner edge sits INSIDE the portal's mouth (a block is `CHUNK_SIZE` px at 1x),
/// so the swirl crosses the spot the player is drawn into rather than ringing politely around it.
const INTAKE_RADIUS_MIN: f32 = 2.5;
const INTAKE_RADIUS_MAX: f32 = 30.0;

/// Particle size in world scale.Scaled by the square root of the zoom rather than the zoom itself.
const INTAKE_SIZE_MIN: f32 = 0.7;
const INTAKE_SIZE_MAX: f32 = 2.3;

/// LCHA colors for a descent's intake particles (violet, magenta, and gold here)!
/// Ordered dimmest first, as `spawnOrbitRing()` requires: it picks by spawn radius,
/// so the last entry is what the mouth itself is lit with and the first is what the rim fades into.
const PORTAL_COLORS = [_]Vec4f32{
    .{ 0.62, 0.21, 5.67, 1.0 },
    .{ 0.72, 0.17, 5.55, 1.0 },
    .{ 0.80, 0.13, 5.50, 1.0 },
    .{ 0.82, 0.14, 1.48, 1.0 },
    .{ 0.50, 0.20, 5.41, 1.0 },
};

/// Copied from `.invportal` colors lazily: green hues.
const INVPORTAL_COLORS = [_]Vec4f32{
    .{ 0.585, 0.113, 2.175, 1.0 },
    .{ 0.675, 0.135, 2.198, 1.0 },
    .{ 0.772, 0.144, 2.060, 1.0 },
    .{ 0.828, 0.181, 2.300, 1.0 },
    .{ 0.592, 0.125, 1.893, 1.0 },
};

/// The palette the running transition's effects draw from.
/// A return dives back down through an ordinary portal, so only an ascent is the odd one out.
inline fn effectColors() []const Vec4f32 {
    return if (isAscending()) &INVPORTAL_COLORS else &PORTAL_COLORS;
}

comptime {
    if (PULL_FRAMES >= TOTAL_FRAMES) @compileError("The player must finish being drawn in before the descent lands.");
    if (OVERLAY_ZOOM <= 1.0 or OVERLAY_ZOOM >= dw.ZOOM_FACTOR) @compileError("OVERLAY_ZOOM must sit between 1x and ZOOM_FACTOR.");
    if (OVERLAY_ZOOM >= @sqrt(@as(f64, dw.ZOOM_FACTOR))) @compileError("OVERLAY_ZOOM must stay below sqrt(ZOOM_FACTOR), or the reveal outruns the cover.");
}

/// Which transition is running. Stored in `GameState` as its integer tag.
pub const Phase = enum(u8) {
    idle,
    /// A D -> D+1 descent through a portal, shaped by `portal_frame`.
    descending,
    /// A D -> D-1 ascent through an inverted portal, the same animation run in reverse.
    ascending,
    /// A D -> D+1 return: dives back through a portal to walk an ascent back one step,
    /// running the zoom past `ZOOM_FACTOR` into a fadeout rather than meeting a preview (see `triggerReturn()`).
    returning,
};

/// Frames the outgoing dive of a return takes. The world commits on the frame this ends,
/// under a screen that has already faded out, so the depth change itself is never seen.
pub const RETURN_DIVE_FRAMES: u32 = 34;
/// Frames the arrival takes, fading the depth landed on back in.
pub const RETURN_ARRIVE_FRAMES: u32 = 18;
/// A return end to end.
pub const RETURN_FRAMES: u32 = RETURN_DIVE_FRAMES + RETURN_ARRIVE_FRAMES;

/// How far the dive keeps zooming, as a multiple of the committed scale.
/// Helps on some level with visual clarity that "we're in preview stage".
pub const RETURN_ZOOM: f64 = 12.0;

/// Fraction of the dive that passes before the fade to black starts,
/// so the zoom actually looks like a dive visually!
const RETURN_FADE_START: f64 = 0.45;

comptime {
    if (RETURN_ZOOM <= dw.ZOOM_FACTOR) @compileError("A return must overshoot ZOOM_FACTOR; stopping there is the descent's job.");
    if (PULL_FRAMES >= RETURN_DIVE_FRAMES) @compileError("The player must finish being drawn in before a return commits.");
    if (RETURN_FADE_START <= 0.0 or RETURN_FADE_START >= 1.0) @compileError("RETURN_FADE_START is a fraction of the dive.");
}

/// Whether the running transition is a descent (rather than an ascent). Only meaningful while zooming.
inline fn isDescending() bool {
    return memory.game.portal_phase == @intFromEnum(Phase.descending);
}

/// Whether an ascent is currently playing. Unlike `isDescending()`, this is safe to ask at any time.
pub inline fn isAscending() bool {
    return memory.game.portal_phase == @intFromEnum(Phase.ascending);
}

/// Whether a return fade is currently playing.
pub inline fn isReturning() bool {
    return memory.game.portal_phase == @intFromEnum(Phase.returning);
}

/// Whether the running transition is one of the two that DISPLAY a preview overlay (descent or ascent).
///
/// A return builds a preview too, but never shows it: it commits under the fade and adopts the result,
/// so the overlay layer (`overlayOpacity()`, `updateOverlayChunks()`) is only wanted for these two.
/// The motion the player sees asks `isActive()`/`hasMotionOverride()`.
pub inline fn isZooming() bool {
    return isDescending() or isAscending();
}

/// Whether the transition moves DEEPER (into D+1): a descent or a return. Its preview reads D parents,
/// which are resident in the `SimBuffer`, so both warm the ancestor cache from it (an ascent cannot).
inline fn goesDeeper() bool {
    return isDescending() or isReturning();
}

/// The frame a return commits on, and the length its preview must be filled within.
inline fn previewDeadline() u32 {
    return if (isReturning()) RETURN_DIVE_FRAMES else fill_deadline;
}

/// One block being swallowed: a purely visual echo of terrain near the player.
/// The world itself is never touched, so no modification is ever written for this.
const Shard = struct {
    /// Entity sprite that this shard is drawn as.
    sprite: Sprite,
    /// Direction it drifts in from, in radians.
    angle: f32,
    /// Distance from the portal it starts at, in viewport pixels.
    radius: f32,
    /// Edge length in viewport pixels.
    size: f32,
    /// Spin over its whole travel, in radians.
    spin: f32,
    /// Frame where this shard appears!
    start_frame: u32,
    /// Frames it takes to reach the portal.
    travel: u32,
};

/// The D+1 transition, worked out once when the descent starts and reinstalled every frame the preview is generated under.
/// Valid only while `ready` is set.
var transition: world.LayerTransition = undefined;

/// D+1 chunks covering everything the overlay can show, taken from `main_allocator`.
var preview: []Chunk = &.{};
/// The coordinate each `preview` slot holds, so a lookup can confirm it found the right chunk.
/// Needed because a window may straddle a quadrant boundary past the horizon,
/// where suffixes wrap and the quadrant flips; comparing suffix offsets alone would mismatch there.
var preview_keys: []Coordinate = &.{};

/// Chunk the grid is measured out from: where the player lands at D+1.
/// The grid is anchored here rather than on its own top-left corner,
/// since that corner can fall off the world (near an edge) and have no coordinate at all to anchor to.
var preview_center: Coordinate = undefined;
/// Chunk offset of the grid's top-left cell from `preview_center`.
var preview_min: [2]i32 = .{ 0, 0 };
var preview_w: u32 = 0;
var preview_h: u32 = 0;

/// How many slots of `preview` hold generated chunks; the rest are still blank.
var filled: u32 = 0;
/// Frame by which the preview must be complete, derived from where the zoom curve crosses `OVERLAY_ZOOM`.
var fill_deadline: u32 = MIN_FILL_FRAMES;

/// The point everything converges on, in subpixels relative to the player's chunk:
/// the spot inside the portal block that maps exactly onto where the player lands at D+1.
/// Zooming into it and then committing therefore lands on the very same world point, with nothing to jump.
var anchor: [2]f64 = .{ 0.0, 0.0 };

/// Where the shards and intake particles converge on (descent) or burst from (ascent),
/// in subpixels relative to the player's chunk.
/// Always the (inverted) portal block; coincides with `anchor` for a descent,
/// but sits apart from it for an ascent, where the camera holds on the player instead.
var effect_center: [2]f64 = .{ 0.0, 0.0 };

/// The spot inside the inverted portal's own chunk that an ascent carries up:
/// what the dive is aimed at and what the landing one depth higher is derived from.
/// Only meaningful while an ascent runs.
var ascend_origin: dw.utils.Vec2i = .{ 0, 0 };

/// The descent's shards. Held in a fixed-sized array rather than a dynamic allocation.
var debris: [SHARD_COUNT]Shard = undefined;
/// How many shards are currently active in the array.
var debris_count: usize = 0;

/// Whether `transition`, `preview`, `anchor` and `debris` describe the descent `GameState` says is running.
/// Cleared by `reset()` and by a load, which is what makes `ensureReady()` rebuild them.
var ready: bool = false;

/// Whether a portal transition (descent or ascent) is currently playing.
pub inline fn isActive() bool {
    return memory.game.portal_phase != @intFromEnum(Phase.idle);
}

/// Smooth 0-1 ease with zero slope at both ends.
inline fn smoothstep(t: f64) f64 {
    const x = std.math.clamp(t, 0.0, 1.0);
    return x * x * (3.0 - 2.0 * x);
}

/// Mild ease-out that gently decelerates to a stop.
inline fn easeOut(t: f64) f64 {
    const x = std.math.clamp(t, 0.0, 1.0);
    return x * (2.0 - x);
}

/// How far through the descent we are, 0 at the first frame and 1 on the committing frame.
inline fn progress() f64 {
    return @as(f64, @floatFromInt(memory.game.portal_frame)) / @as(f64, @floatFromInt(TOTAL_FRAMES));
}

/// Exponent of the zoom at progress `t`, where the zoom is `ZOOM_FACTOR` raised to it.
/// Using this for an exponent makes each frame scale the view by a visually consistent ratio
/// (similar to how actual fractal zoom videos work)!
///
/// Squaring the `smoothstep()` keeps the slope at zero on both ends (so it eases in and out),
/// while holding the early frames low enough for the preview to finish generating before the overlay appears.
inline fn zoomCurve(t: f64) f64 {
    const s = smoothstep(t);
    return s * s;
}

/// Signed zoom exponent for this frame: a descent zooms in (+), an ascent zooms out (-).
inline fn zoomSign() f64 {
    return if (isDescending()) 1.0 else -1.0;
}

/// How much the world's zoom is multiplied by this frame.
/// A descent runs 1x -> `ZOOM_FACTOR` (zoom in); an ascent runs 1x -> `1 / ZOOM_FACTOR` (zoom out).
/// `overlayScale()` cancels the factor out, which is why reaching the last frame lands on the committed view.
pub fn zoomFactor() f64 {
    @setFloatMode(.optimized);
    if (isReturning()) {
        // Nothing left to zoom once it has committed: the arrival is the landed world fading in.
        if (memory.game.portal_frame >= RETURN_DIVE_FRAMES) return 1.0;
        return std.math.pow(f64, RETURN_ZOOM, zoomCurve(returnDiveProgress()));
    }
    if (!isZooming()) return 1.0;
    return std.math.pow(f64, @as(f64, dw.ZOOM_FACTOR), zoomSign() * zoomCurve(progress()));
}

/// The zoom multiplier at an arbitrary frame, for planning ahead of time.
fn zoomFactorAt(frame: u32) f64 {
    const t = @as(f64, @floatFromInt(frame)) / @as(f64, @floatFromInt(TOTAL_FRAMES));
    return std.math.pow(f64, @as(f64, dw.ZOOM_FACTOR), zoomSign() * zoomCurve(t));
}

/// Scale multiplier the overlay layer is drawn at, relative to `camera_scale`.
///
/// The overlay is the depth being ENTERED (D+1 descending, D-1 ascending),
/// so it sits at a factor of `ZOOM_FACTOR` from the live layer:
/// descending it is `ZOOM_FACTOR` smaller, ascending `ZOOM_FACTOR` larger.
///
/// Either way the factor cancels `zoomFactor()` on the last frame,
/// so the overlay arrives at exactly `camera_scale` and the hand-off to the new depth is invisible.
pub fn overlayScale() f64 {
    @setFloatMode(.optimized);
    const factor: f64 = if (isDescending()) 1.0 / @as(f64, dw.ZOOM_FACTOR) else dw.ZOOM_FACTOR;
    return zoomFactor() * factor;
}

/// Overlay scale at its most zoomed-out (widest footprint), which is what `allocatePreview()` sizes for.
/// Descending that is the instant it appears (`OVERLAY_ZOOM / ZOOM_FACTOR`);
/// ascending it is the committed frame (`1.0`), since the D-1 layer starts zoomed in and pulls out to rest.
fn widestOverlayScale() f64 {
    return if (isDescending()) OVERLAY_ZOOM / @as(f64, dw.ZOOM_FACTOR) else 1.0;
}

/// Zoom at which the overlay begins to reveal, driving `planFill()`'s deadline.
/// Mirrored for an ascent: instead of zooming past `OVERLAY_ZOOM` in, it zooms past its reciprocal out.
inline fn revealZoom() f64 {
    return if (isDescending()) OVERLAY_ZOOM else 1.0 / OVERLAY_ZOOM;
}

/// Whether `zoom` has passed the reveal threshold, accounting for the zoom direction.
inline fn pastReveal(zoom: f64) bool {
    return if (isDescending()) zoom > revealZoom() else zoom < revealZoom();
}

/// Zoom-curve exponent at which the overlay has completely covered the live layer.
/// Only used on depth increase for the second chunk batch drawing!
fn coverCurve() f64 {
    @setFloatMode(.optimized);
    if (!isAscending()) return 1.0;
    // The zoom is ZOOM_FACTOR raised to the curve, so the crossing is a plain change of base.
    return 1.0 - @log(OVERLAY_ZOOM) / @log(@as(f64, dw.ZOOM_FACTOR));
}

/// Opacity the overlay layer (chunks and background alike) is drawn at.
///
/// The live layer is never faded: it stays at full strength and this is the only knob moved,
/// so the new depth arrives *over* a solid image rather than the two meeting in the middle as a dissolve.
pub fn overlayOpacity() f64 {
    @setFloatMode(.optimized);
    if (!isZooming()) return 0.0;
    const start = zoomCurve(@as(f64, @floatFromInt(fill_deadline)) / @as(f64, @floatFromInt(TOTAL_FRAMES)));
    const end = coverCurve();
    std.debug.assert(end > start);

    const now = zoomCurve(progress());
    if (now <= start) return 0.0;
    if (now >= end) return 1.0;

    const t = easeOut((now - start) / (end - start));
    return t * t;
}

/// Whether to skip rendering the live layer. The player must still be rendered!
pub fn liveLayerHidden() bool {
    if (!isActive()) return false;
    return worldOpacity() <= 0.0 or overlayOpacity() >= 1.0;
}

/// How far the player has been drawn into the portal, 0 to 1.
/// Both directions pull: a descent is swallowed by the portal below, an ascent is drawn up through the inverted one above.
inline fn pullProgress() f64 {
    if (!hasMotionOverride()) return 0.0;
    const frame: f64 = @floatFromInt(@min(memory.game.portal_frame, PULL_FRAMES));
    return frame / @as(f64, @floatFromInt(PULL_FRAMES));
}

/// How hard the world is shaking this frame, 0 (still) to 1 (full tremor).
/// Increases as the zoom progresses, with a minor fade-out at the end (see `render/chunk.zig`'s updateShake()).
pub fn shakeIntensity() f32 {
    @setFloatMode(.optimized);
    if (!isActive()) return 0.0;
    // if returning then there's no need to shake
    if (isReturning() and memory.game.portal_frame >= RETURN_DIVE_FRAMES) return 0.0;

    const p = curveProgress();
    const base_shake = 0.25 + 0.75 * zoomCurve(p);

    const fade = if (p >= 0.9)
        @max(0.0, (1.0 - p) / 0.1)
    else
        1.0;

    return @floatCast(base_shake * fade);
}

/// Rate the background clock advances at, eased to a standstill as the player is drawn in.
pub fn backgroundRate() f64 {
    @setFloatMode(.optimized);
    if (!isActive()) return 1.0;
    return 1.0 - smoothstep(pullProgress());
}

/// Starts a descent through the portal at `coord`'s block (`bx`, `by`). Ignored if one is already running.
pub fn trigger(coord: Coordinate, bx: u4, by: u4) void {
    beginTransition(.descending, coord, bx, by);
}

/// Starts an ascent through the inverted portal at `coord`'s block (`bx`, `by`).
/// The block is recorded only so the effects can emanate from it;
/// the transition itself derives entirely from the player's position (see `world.computeParentLayer()`).
/// Ignored if one is running (already).
pub fn triggerAscend(coord: Coordinate, bx: u4, by: u4) void {
    // The base layer has no parent to rise into; the indicator is already hidden there,
    // so this is only the backstop for any other caller.
    if (!world.canAscend()) return;
    beginTransition(.ascending, coord, bx, by);
}

/// Starts a return: dives back through the portal at `coord`, landing on the portal the last ascent was
/// taken through. The player is drawn into the portal exactly as a descent draws them in, so nothing
/// about the move reads as a teleport.
///
/// Shaped like the descent but not the same: with no preview to line up against, the zoom is free to
/// overshoot `ZOOM_FACTOR` and run away into a fadeout, which is what keeps a return looking identical
/// at any depth. Which portal was clicked only decides where the dive is aimed; the route back is the
/// recorded `AscentStep`, so any portal serves as the way down.
/// No-op unless the player is actually above their deepest depth.
pub fn triggerReturn(coord: Coordinate, bx: u4, by: u4) void {
    if (isActive() or !world.canRetrace()) return;
    beginTransition(.returning, coord, bx, by);
}

/// How far through the DIVE a return is, 0 to 1, holding at 1 for the arrival.
/// Everything visible about a return is over by the time it commits, so this is what the visual
/// curves run on rather than the whole length.
inline fn returnDiveProgress() f64 {
    const f: f64 = @floatFromInt(@min(memory.game.portal_frame, RETURN_DIVE_FRAMES));
    return f / @as(f64, @floatFromInt(RETURN_DIVE_FRAMES));
}

/// Whether the transition is currently driving the camera and player itself.
/// False through a return's arrival: the world has already committed by then and the player is at
/// their landing spot, so the ordinary interpolation takes back over.
pub inline fn hasMotionOverride() bool {
    if (!isActive()) return false;
    return !isReturning() or memory.game.portal_frame < RETURN_DIVE_FRAMES;
}

/// How far through whichever part of the transition drives the visuals, 0 to 1.
inline fn curveProgress() f64 {
    return if (isReturning()) returnDiveProgress() else progress();
}

/// Opacity the whole world (background and tiles alike) is drawn at.
///
/// Always 1.0 except during a "dive return", which fades out over the back of its dive and back in on arrival.
/// The commit lands between the two, on a screen that is already empty, so the depth change is never seen.
pub fn worldOpacity() f64 {
    if (!isReturning()) return 1.0;
    const frame = memory.game.portal_frame;
    if (frame < RETURN_DIVE_FRAMES) {
        // Holds at full through the early dive, so the zoom is what reads, then drops to nothing by
        // the frame the world commits.
        const t = returnDiveProgress();
        if (t <= RETURN_FADE_START) return 1.0;
        return 1.0 - smoothstep((t - RETURN_FADE_START) / (1.0 - RETURN_FADE_START));
    }
    const t = @as(f64, @floatFromInt(frame - RETURN_DIVE_FRAMES)) / @as(f64, @floatFromInt(RETURN_ARRIVE_FRAMES));
    return smoothstep(t);
}

fn beginTransition(phase: Phase, coord: Coordinate, bx: u4, by: u4) void {
    if (isActive()) return;

    // Every menu is bound to a block at the depth being left, and the world is frozen from here until
    // the commit, so none of them may act. `mod_store.beginWrite()` asserts the same thing from the
    // other side, since the menus are the only writers that outlive the tick gate in `handleTick()`.
    dw.indicators.closeAllMenus();

    const g = &memory.game;
    g.portal_chunk = coord.suffix;
    g.portal_quadrant = coord.quadrant;
    g.portal_bx = bx;
    g.portal_by = by;
    g.portal_frame = 0;
    g.portal_phase = @intFromEnum(phase);

    ready = false;
    ensureReady();
}

/// The portal that started the running descent, as recorded in `GameState`.
inline fn portalCoord() Coordinate {
    return .{
        .suffix = memory.game.portal_chunk,
        .quadrant = @intCast(memory.game.portal_quadrant & 3),
    };
}

/// Works out everything a descent needs that a save does not carry.
/// Safe to call repeatedly; only the first call after a trigger (or a load) does any work.
fn ensureReady() void {
    if (ready or !isActive()) return;

    const bx: u4 = @intCast(memory.game.portal_bx & 15);
    const by: u4 = @intCast(memory.game.portal_by & 15);

    if (isReturning()) {
        if (memory.game.portal_frame >= RETURN_DIVE_FRAMES) {
            // done!
            ready = true;
            return;
        }
        // A return dives back to a depth already visited, at a spot already recorded,
        // so its D+1 transition is read straight back rather than recomputed (see world.computeRetraceLayer()).
        transition = world.computeRetraceLayer(world.retraceStep().?);
        computeEffectcenter(bx, by);
        anchor = effect_center;
        allocatePreview();
        collectDebris();
        ready = true;
        return;
    }

    if (isDescending()) {
        // landing is on the portal block itself since the sucky camera centering effect+visuals look better that way
        transition = world.computeLayer(portalCoord(), bx, by, .block_floor);
        computeAnchor(bx, by);
    } else {
        // player rises thru inverted portal as well
        ascend_origin = world.blockStandPos(bx, by);
        transition = world.computeParentLayer(portalCoord(), ascend_origin);
        anchor = chunkRelative(ascend_origin);
    }
    // the effects always radiate from the (inverted) portal block, wherever the camera settles
    computeEffectcenter(bx, by);

    planFill();
    allocatePreview();
    collectDebris();
    ready = true;
}

/// Re-expresses a position inside the portal's chunk as subpixels relative to the PLAYER's chunk,
/// which is the space the camera, the player and `worldToScreen()` all work in.
fn chunkRelative(pos: dw.utils.Vec2i) [2]f64 {
    const player_coord = memory.game.getPlayerCoord();
    const portal = portalCoord();
    // Wrapping subtraction gives the signed chunk delta, matching how `moveAtDepth()` steps.
    const chunk_dx: i64 = @bitCast(portal.suffix[0] -% player_coord.suffix[0]);
    const chunk_dy: i64 = @bitCast(portal.suffix[1] -% player_coord.suffix[1]);
    return .{
        @floatFromInt(chunk_dx * dw.SUBPIXELS_IN_CHUNK + pos[0]),
        @floatFromInt(chunk_dy * dw.SUBPIXELS_IN_CHUNK + pos[1]),
    };
}

/// Places `effect_center` on the portal block's center, in subpixels relative to the player's chunk.
/// This is where shards and intake particles emanate from, for both directions.
fn computeEffectcenter(bx: u4, by: u4) void {
    const half = @divExact(dw.CHUNK_SIZE_SQ, 2);
    effect_center = chunkRelative(.{
        @as(i64, bx) * dw.CHUNK_SIZE_SQ + half,
        @as(i64, by) * dw.CHUNK_SIZE_SQ + half,
    });
}

/// Locates the D-space point matching where the player lands at D+1.
///
/// The landing sits at some offset inside the portal block's child region; dividing that offset by
/// `ZOOM_FACTOR` gives the same spot expressed in the parent block,
/// which is what the camera has to arrive at for the commit to be seamless.
fn computeAnchor(bx: u4, by: u4) void {
    const g = &memory.game;
    const player_coord = g.getPlayerCoord();
    const portal = portalCoord();

    // Wrapping subtraction gives the signed chunk delta, matching how `moveAtDepth()` steps.
    const chunk_dx: i64 = @bitCast(portal.suffix[0] -% player_coord.suffix[0]);
    const chunk_dy: i64 = @bitCast(portal.suffix[1] -% player_coord.suffix[1]);

    // Offset of the landing within its child region, brought back into parent-block scale.
    const region: i64 = dw.CHUNK_SIZE_SQ * dw.ZOOM_FACTOR;
    const in_region_x: f64 = @floatFromInt(@mod(transition.new_pos[0], region));
    const in_region_y: f64 = @floatFromInt(@mod(transition.new_pos[1], region));

    const block: f64 = @floatFromInt(dw.CHUNK_SIZE_SQ);
    anchor = .{
        @as(f64, @floatFromInt(chunk_dx * dw.SUBPIXELS_IN_CHUNK)) +
            @as(f64, @floatFromInt(bx)) * block + in_region_x / dw.ZOOM_FACTOR,
        @as(f64, @floatFromInt(chunk_dy * dw.SUBPIXELS_IN_CHUNK)) +
            @as(f64, @floatFromInt(by)) * block + in_region_y / dw.ZOOM_FACTOR,
    };
}

/// Finds the last frame the zoom is still at or below `OVERLAY_ZOOM`,
/// which is the deadline the preview has to be complete by. Derived from the curve rather than hard-coded,
/// so retuning the timing cannot silently let the overlay appear over half-generated chunks.
fn planFill() void {
    fill_deadline = TOTAL_FRAMES;
    var frame: u32 = 0;
    while (frame <= TOTAL_FRAMES) : (frame += 1) {
        if (pastReveal(zoomFactorAt(frame))) {
            fill_deadline = frame;
            break;
        }
    }
    // An ascent generates its whole (smaller) parent preview up front in ensureReady()
    // so it has no fill floor to honour; only a descent spreads generation and needs the assert!
    if (isDescending()) std.debug.assert(fill_deadline >= MIN_FILL_FRAMES);
}

/// Sizes and clears the D+1 preview to cover the widest view the overlay can ever show.
///
/// That widest view is the instant the overlay appears, at `OVERLAY_ZOOM`: the D+1 layer is drawn at
/// `zoomFactor() / ZOOM_FACTOR`, which only grows from there, so the footprint only ever shrinks.
fn allocatePreview() void {
    const g = &memory.game;
    // The scale the overlay layer is drawn at when its footprint is widest (its most zoomed-out state).
    const widest_zoom = g.camera_scale * widestOverlayScale();

    const subpixels_per_chunk: f64 = @floatFromInt(dw.SUBPIXELS_IN_CHUNK);
    const half_w_sp = (@as(f64, dw.SCREEN_WIDTH_HALF) / widest_zoom) * dw.CHUNK_SIZE;
    const half_h_sp = (@as(f64, dw.SCREEN_HEIGHT_HALF) / widest_zoom) * dw.CHUNK_SIZE;

    // The camera has arrived on the landing point by the time the overlay shows so D+1 is centered!
    const cam_x: f64 = @floatFromInt(transition.new_pos[0]);
    const cam_y: f64 = @floatFromInt(transition.new_pos[1]);

    const margin: i32 = @intCast(dw.lighting.CHUNK_MARGIN);
    const min_cx = @as(i32, @intFromFloat(@floor((cam_x - half_w_sp) / subpixels_per_chunk))) - margin;
    const min_cy = @as(i32, @intFromFloat(@floor((cam_y - half_h_sp) / subpixels_per_chunk))) - margin;
    const max_cx = @as(i32, @intFromFloat(@floor((cam_x + half_w_sp) / subpixels_per_chunk))) + margin;
    const max_cy = @as(i32, @intFromFloat(@floor((cam_y + half_h_sp) / subpixels_per_chunk))) + margin;

    const half_sim: i32 = world.SIM_BUFFER_WIDTH / 2;
    const lo_x = @min(min_cx, -half_sim);
    const lo_y = @min(min_cy, -half_sim);
    const hi_x = @max(max_cx, half_sim - 1);
    const hi_y = @max(max_cy, half_sim - 1);

    preview_w = @intCast(hi_x - lo_x + 1);
    preview_h = @intCast(hi_y - lo_y + 1);
    preview_min = .{ lo_x, lo_y };
    preview_center = .{ .suffix = transition.player_chunk, .quadrant = transition.player_quadrant };

    const needed = @as(usize, preview_w) * @as(usize, preview_h);
    if (preview.len != needed) {
        freeBuffers();
        preview = memory.main_allocator.alloc(Chunk, needed) catch memory.oom();
        preview_keys = memory.main_allocator.alloc(Coordinate, needed) catch memory.oom();
    }
    filled = 0;
}

/// Hands the preview allocations back, leaving the rest of the descent's state alone.
fn freeBuffers() void {
    if (preview.len != 0) memory.main_allocator.free(preview);
    if (preview_keys.len != 0) memory.main_allocator.free(preview_keys);
    preview = &.{};
    preview_keys = &.{};
}

/// Samples the block types around the player, then lays out the shards that will be swallowed.
///
/// Read-only with respect to the world: these are decorative copies, and no modification is written.
/// Everything is drawn from a seeded generator so a reload lays out the identical descent.
fn collectDebris() void {
    @setFloatMode(.optimized);
    const g = &memory.game;

    // Sample the surrounding block types. Only the set of types matters; where each one sat does not,
    // since the shards are scattered on a ring rather than flown in from their real positions.
    var palette: [MAX_PALETTE]Sprite = undefined;
    var palette_len: usize = 0;

    const player_coord = g.getPlayerCoord();
    const player_bx: i32 = g.getBlockXInChunk();
    const player_by: i32 = g.getBlockYInChunk();

    var dy: i32 = -DEBRIS_RADIUS;
    while (dy < DEBRIS_RADIUS) : (dy += 1) {
        var dx: i32 = -DEBRIS_RADIUS;
        while (dx < DEBRIS_RADIUS) : (dx += 1) {
            const target_bx = player_bx + dx;
            const target_by = player_by + dy;
            const coord = player_coord.move(.{
                @divFloor(target_bx, dw.CHUNK_SIZE),
                @divFloor(target_by, dw.CHUNK_SIZE),
            }) orelse continue;
            const chunk = world.SimBuffer.get(coord) orelse continue;
            const block = chunk.getBlock(
                @intCast(@mod(target_bx, dw.CHUNK_SIZE)),
                @intCast(@mod(target_by, dw.CHUNK_SIZE)),
            );
            // Air has nothing to show, and the portal is the thing doing the swallowing.
            if (block.isEmpty() or block.id == .portal) continue;

            palette[palette_len] = block.id;
            palette_len += 1;
        }
    }

    // Standing in open air leaves nothing to swallow; the particles carry the effect alone.
    if (palette_len == 0) {
        clearDebris();
        return;
    }

    debris_count = SHARD_COUNT;

    var rng = dw.seeding.ChaCha12.init(&dw.seeding.mixBaseSeed(g.seed, .portal_debris));
    const total: f64 = @floatFromInt(if (isReturning()) RETURN_DIVE_FRAMES else TOTAL_FRAMES);
    const span = SHARD_SPAWN_SPAN * total;

    for (&debris) |*shard| {
        // Square-rooting a uniform value biases the start times later, so the intake visibly builds
        // instead of arriving all at once.
        const when = @sqrt(rng.float(f64));
        shard.* = .{
            .sprite = palette[@intCast(rng.next() % palette_len)],
            .angle = @floatCast(rng.float(f64) * std.math.tau),
            .radius = SHARD_RADIUS_MIN + (SHARD_RADIUS_MAX - SHARD_RADIUS_MIN) * rng.float(f32),
            // biased to be smaller!
            .size = SHARD_SIZE * (0.35 + 0.75 * rng.float(f32) * rng.float(f32)),
            .spin = (rng.float(f32) - 0.5) * 6.0,
            .start_frame = @intFromFloat(when * span),
            .travel = SHARD_TRAVEL_MIN + @as(u32, @intCast(rng.next() % (SHARD_TRAVEL_MAX - SHARD_TRAVEL_MIN + 1))),
        };
    }
}

/// Drops every active shard. Nothing is freed: the array is fixed-size and lives with the module.
fn clearDebris() void {
    debris_count = 0;
}

/// Ceiling on the parent region handed to the ancestor cache, as a radius in D chunks.
/// 11x11 is already more than the hot tier holds (`AncestorCache.HOT_SIZE`),
/// so seeding past this would only evict what it just inserted.
const ANCESTOR_SEED_MAX_RADIUS: i64 = 5;

/// Radius in D chunks that covers every parent the preview will read.
///
/// Derived from the window rather than assumed: a zoomed-out camera can make the preview far wider than the `SimBuffer` window,
/// and a radius that fails to reach leaves exactly the cold ancestor walk this seeding exists to avoid.
/// Each D chunk covers `ZOOM_FACTOR` child chunks,
/// plus one for the generator's 6x6 block neighbourhood spilling into the next chunk over, plus one to round up.
fn ancestorSeedRadius() i64 {
    const far_x = @max(@abs(preview_min[0]), @abs(preview_min[0] + @as(i32, @intCast(preview_w)) - 1));
    const far_y = @max(@abs(preview_min[1]), @abs(preview_min[1] + @as(i32, @intCast(preview_h)) - 1));
    const reach = @divTrunc(@as(i64, @max(far_x, far_y)), dw.ZOOM_FACTOR) + 2;
    return @min(reach, ANCESTOR_SEED_MAX_RADIUS);
}

/// Copies the D chunks the preview reads as parents into the ancestor cache, keyed for the depth the preview generates at.
///
/// `AncestorCache` indexes tiers RELATIVE to `memory.game.depth` (see `relativeTier()`),
/// so installing the transition shifts every existing entry out of reach:
/// a parent at D lands on the tier that holds D-1, misses, and re-derives itself from D-1,
/// which misses in turn, all the way down the chain.
///
/// The `SimBuffer` already holds these chunks fully materialized, but `getCachedChunk()` only consults it when `key.depth == game.depth`,
/// which is false here. Copying them across turns every parent lookup into a hit,
/// so the preview never regenerates a chunk that is already in memory.
///
/// Precondition: the transition must already be installed, so `game.depth` is the preview's depth.
fn seedAncestorsFromSim(center: Coordinate, parent_depth: u64) void {
    const radius = ancestorSeedRadius();
    var dy: i64 = -radius;
    while (dy <= radius) : (dy += 1) {
        var dx: i64 = -radius;
        while (dx <= radius) : (dx += 1) {
            const coord = center.moveAtDepth(.{ dx, dy }, parent_depth) orelse continue;
            // Resident chunks only: anything absent would have to be generated either way.
            const chunk = world.SimBuffer.get(coord) orelse continue;
            _ = dw.ancestor.ancestor_cache.insert(coord.asDepthCoordinate(parent_depth), chunk.*);
        }
    }
}

/// Preview chunks to generate per frame. `CHUNKS_PER_FRAME` in the ordinary case, raised when the
/// window is big enough (zoomed-out camera) or the deadline near enough that the baseline would miss it.
///
/// A return has far fewer frames to fill in (`RETURN_DIVE_FRAMES` vs `TOTAL_FRAMES`), so this hands it
/// a proportionally higher rate rather than overrunning its commit with a half-built preview.
inline fn chunksPerFrame() u32 {
    const total: u32 = @intCast(preview.len);
    const deadline = previewDeadline();
    return @max(CHUNKS_PER_FRAME, (total + deadline - 1) / deadline);
}

/// Generates the next `count` preview chunks.
///
/// Chunk generation reads the depth, quadrant seeds and rebase origins straight out of the globals,
/// so the D+1 transition is installed for the duration and taken back off afterwards.
/// The live D world is untouched: `restoreLayer()` is the exact inverse of `installLayer()`.
fn fillPreview(count: u32) void {
    if (filled >= preview.len) return;

    // Captured before the transition goes in, while these still describe D.
    // The D parents the deeper preview reads live around the player's current chunk
    // (a descent's portal, and a return's landing, are both within a few blocks of it).
    const parent_coord = memory.game.getPlayerCoord();
    const parent_depth = memory.game.depth;

    const snapshot = world.snapshotLayer(transition.depth);
    world.installLayer(transition);
    defer world.restoreLayer(snapshot);

    // Going-deeper only: it warms the D parents the D+1 preview reads, which are resident in the SimBuffer.
    // An ascent reads D-2 parents (shallower than the live D world),
    // which are not resident and would key into a negative tier relative to the installed D-1 depth, so it is skipped.
    if (filled == 0 and goesDeeper()) seedAncestorsFromSim(parent_coord, parent_depth);

    var made: u32 = 0;
    while (made < count and filled < preview.len) : ({
        made += 1;
        filled += 1;
    }) {
        const gx: i64 = @as(i64, preview_min[0]) + @as(i64, @intCast(filled % preview_w));
        const gy: i64 = @as(i64, preview_min[1]) + @as(i64, @intCast(filled / preview_w));
        const slot = &preview[filled];

        if (preview_center.moveAtDepth(.{ gx, gy }, transition.depth)) |coord| {
            preview_keys[filled] = coord;
            world.materializeChunk(slot, coord.asDepthCoordinate(transition.depth));
        } else {
            // Past the world edge, matching how updateVisibleChunks() blanks the same case.
            // No real coordinate exists, so mark the slot unmatchable rather than leaving it undefined.
            preview_keys[filled] = .{ .suffix = .{ 0, 0 }, .quadrant = 0 };
            @memset(&slot.blocks, memory.Block.empty);
        }
    }
}

/// The generated D+1 chunk at `coord`, or null when it is outside the preview window or not yet made.
/// The overlay renders a null as empty space, which can only happen before the overlay is visible.
pub fn previewChunk(coord: Coordinate) ?*const Chunk {
    if (!ready or preview.len == 0) return null;

    // suffix subtraction wraps the same way `moveAtDepth()` does
    // the stored key then confirms it really is the right chunk!
    const dx = (coord.suffix[0] -% preview_center.suffix[0]) -% @as(u64, @bitCast(@as(i64, preview_min[0])));
    const dy = (coord.suffix[1] -% preview_center.suffix[1]) -% @as(u64, @bitCast(@as(i64, preview_min[1])));
    if (dx >= preview_w or dy >= preview_h) return null;

    const idx = dy * @as(u64, preview_w) + dx;
    if (idx >= filled) return null;
    if (!preview_keys[@intCast(idx)].eql(coord)) return null;
    return &preview[@intCast(idx)];
}

/// The overlay's transition (the depth being entered).
/// Asserts that `isActive()` is true for validity.
pub fn overlayTransition() world.LayerTransition {
    std.debug.assert(isActive());
    return transition;
}

/// Camera position for this frame, in subpixels relative to the player's chunk.
/// Easing effect; doesn't rewrite `game.camera_pos`.
pub fn cameraOverride() [2]f64 {
    const g = &memory.game;
    const t = smoothstep(pullProgress());
    return .{
        @as(f64, @floatFromInt(g.camera_pos[0])) * (1.0 - t) + anchor[0] * t,
        @as(f64, @floatFromInt(g.camera_pos[1])) * (1.0 - t) + anchor[1] * t,
    };
}

/// Player position for this frame, in subpixels relative to the player's chunk.
/// Accelerates into the portal rather than easing out of it, so the pull reads as a grab.
pub fn playerOverride() [2]f64 {
    const g = &memory.game;
    const p = pullProgress();
    const t = p * p; // ease in: slow to give, then snatched
    return .{
        @as(f64, @floatFromInt(g.player_pos[0])) * (1.0 - t) + anchor[0] * t,
        @as(f64, @floatFromInt(g.player_pos[1])) * (1.0 - t) + anchor[1] * t,
    };
}

/// How much the player sprite is squeezed as the portal takes it.
///
/// Recovers to 1 by the last frame rather than staying small, so the commit has nothing to pop back from.
pub fn playerScale() f32 {
    @setFloatMode(.optimized);
    if (!isActive()) return 1.0;
    const SQUEEZE = 0.55;
    // Undone in step with the zoom, so both arrive at their committed values on the same frame.
    return @floatCast(1.0 - SQUEEZE * smoothstep(pullProgress()) * (1.0 - zoomCurve(curveProgress())));
}

/// Converts a world position (subpixels relative to the player's chunk) into viewport pixels,
/// using the same mapping the tile grid uses so effects stay locked to the blocks.
fn worldToScreen(sub: [2]f64) Vec2f32 {
    const zoom = memory.game.camera_scale * zoomFactor();
    const cam = cameraOverride();
    return .{
        @floatCast(@as(f64, dw.SCREEN_WIDTH_HALF) + (sub[0] - cam[0]) * zoom / dw.CHUNK_SIZE_FLOAT),
        @floatCast(@as(f64, dw.SCREEN_HEIGHT_HALF) + (sub[1] - cam[1]) * zoom / dw.CHUNK_SIZE_FLOAT),
    };
}

/// Where the effects converge this frame, in viewport pixels.
///
/// Not simply the portal block: for the whole pull the player is still out where they were standing,
/// and a swirl centered on the mouth from frame zero reads as an effect playing next to them rather
/// than one acting on them. So it starts on the player and is carried onto the mouth as they are
/// drawn in, arriving exactly when they do.
///
/// Both ends converge anyway (`playerOverride()` eases onto `anchor`, which is the same block
/// `effect_center` measures), so this only shapes the pull; afterwards it is `effect_center` outright.
fn effectOrigin() Vec2f32 {
    const t = smoothstep(pullProgress());
    const player = playerOverride();
    return worldToScreen(.{
        player[0] * (1.0 - t) + effect_center[0] * t,
        player[1] * (1.0 - t) + effect_center[1] * t,
    });
}

/// Draws the descent's effects: the terrain being swallowed.
/// Called once per render frame from `entity.updateEntities()`.
/// The intake particles are spawned from `tick()` instead, so their density does not ride the frame rate.
pub fn drawEffects() void {
    @setFloatMode(.optimized);
    if (!isActive() or !ready) return;
    drawDebris(effectOrigin());
}

/// Fade factor for portal-related visual elements (shards n' particles) near the end of the descent.
pub fn getDescentFade() f32 {
    @setFloatMode(.optimized);
    if (!isActive()) return 1.0;
    const t = curveProgress();
    if (t < 0.8) return 1.0;
    return @floatCast((1.0 - t) / 0.2);
}

/// Draws each shard falling into the portal.
///
/// Purely screen-space: the ring, the sizes and the travel are all in viewport pixels,
/// so the zoom ramping to `ZOOM_FACTOR` underneath costs nothing here and the debris keeps arriving throughout.
fn drawDebris(center: Vec2f32) void {
    const frame = memory.game.portal_frame;

    for (debris[0..debris_count]) |*shard| {
        if (frame < shard.start_frame) continue;
        const travelled: f64 = @floatFromInt(frame - shard.start_frame);
        const u = @min(travelled / @as(f64, @floatFromInt(shard.travel)), 1.0);
        if (u >= 1.0) continue; // already swallowed

        const eased: f32 = @floatCast(u * u);
        // Descent and return both draw terrain inward to be swallowed; only an ascent throws it
        // outward, as the world opens up around the player.
        const distance = shard.radius * (if (isAscending()) eased else 1.0 - eased);

        // Terrain rides the same vortex the intake particles orbit on, rather than falling down a
        // spoke of its own: two motion fields over one portal is what makes the effect read as
        // unrelated systems sharing a screen. The sweep tightens as the travel runs on, so a shard
        // being swallowed accelerates into the mouth; an ascent throws the same curve back outward.
        const swept = shard.angle + SHARD_SWIRL * eased / (1.0 - SHARD_SWIRL_TIGHTEN * eased);
        const pos: Vec2f32 = .{
            center[0] + @cos(swept) * distance,
            center[1] + @sin(swept) * distance,
        };

        // Fades up out of nothing, then fades out right as it enters the center.
        const appear = @min(eased * 6.0, 1.0);
        const alpha = appear * (1.0 - eased) * getDescentFade();

        const glow = eased * eased;
        dw.entity.addEntity(.{
            .sprite = shard.sprite,
            .position = pos,
            .size = shard.size * (1.0 - 0.75 * eased),
            .rotation = shard.spin * eased,
            .lcha = .{
                1.0 + SHARD_GLOW_LIGHT * glow,
                SHARD_GLOW_CHROMA * glow,
                SHARD_GLOW_HUE * glow,
                alpha,
            },
        });
    }
}

/// Particles thrown by the swallow. Big enough to punctuate, since it fires exactly once.
const SWALLOW_SPARKS: usize = 120;

/// The kick the mouth gives on the frame the player finishes being drawn in.
///
/// Keyed to that exact frame rather than a range, so a save resumed past it cannot fire a second time.
/// Half of it is thrown clear and half is a tight counter-swirl straight back down,
/// so the moment still reads as the portal taking something rather than as an explosion.
fn spawnSwallow() void {
    @setFloatMode(.optimized);
    const zoom: f32 = @floatCast(memory.game.camera_scale * @min(zoomFactor(), @as(f64, dw.ZOOM_FACTOR)));
    const center = effectOrigin();
    const size_scale = @sqrt(zoom);

    dw.particles.spawnBurst(center, effectColors(), .{
        .count = SWALLOW_SPARKS,
        .speed_min = 0.7 * zoom,
        .speed_max = 3.0 * zoom,
        .size_min = INTAKE_SIZE_MIN * size_scale,
        .size_max = INTAKE_SIZE_MAX * 1.6 * size_scale,
        .lifetime_min = 10,
        .lifetime_max = 26,
    });

    dw.particles.spawnOrbitRing(center, effectColors(), .{
        .count = SWALLOW_SPARKS / 2,
        .radius_min = INTAKE_RADIUS_MIN * zoom,
        .radius_max = INTAKE_RADIUS_MAX * 0.6 * zoom,
        .size_min = INTAKE_SIZE_MIN * size_scale,
        .size_max = INTAKE_SIZE_MAX * size_scale,
        .travel_min = 6,
        .travel_max = 14,
        .swirl = 1.6,
    });
}

/// Emits the portal's inward-falling particles, growing more insistent as the descent builds.
///
/// Deliberately outlives the intake fade: the particles are still going strong while the D+1 layer comes up underneath them,
/// which is what keeps that hand-over from reading as a dissolve.
/// They only thin out over the closing stretch, once the zoom alone carries the shot.
fn spawnIntake() void {
    @setFloatMode(.optimized);
    const t = progress();
    // Ramp in over the intake, hold through the overlay's arrival, then ease away at the very end.
    const ramp = smoothstep(@as(f64, @floatFromInt(memory.game.portal_frame)) / @as(f64, @floatFromInt(fill_deadline)));
    const TAIL_START = 0.8;
    const tail = if (t <= TAIL_START) 1.0 else 1.0 - smoothstep((t - TAIL_START) / (1.0 - TAIL_START));
    const intensity = ramp * tail;
    if (intensity <= 0.0) return;

    const zoom: f32 = @floatCast(memory.game.camera_scale * zoomFactor());

    // create a rhythm effect to sell an interesting effect here!
    const wave = 0.5 - 0.5 * @cos(@as(f64, @floatFromInt(memory.game.portal_frame)) * INTAKE_PULSE_RATE);
    const surge = intensity * intensity * (INTAKE_PULSE_FLOOR + (1.0 - INTAKE_PULSE_FLOOR) * wave);
    const count: usize = @intFromFloat(3.0 + 46.0 * surge);

    const cap: u16 = @intFromFloat(@round(24.0 - 14.0 * progress()));
    if (cap > 2) {
        dw.particles.spawnOrbitRing(effectOrigin(), effectColors(), .{
            .count = count,
            // Held in world scale so the ring keeps hugging the mouth as the view zooms.
            .radius_min = INTAKE_RADIUS_MIN * zoom,
            .radius_max = INTAKE_RADIUS_MAX * zoom,
            .size_min = INTAKE_SIZE_MIN * @sqrt(zoom),
            .size_max = INTAKE_SIZE_MAX * @sqrt(zoom),
            .travel_min = @min(cap, 8),
            .travel_max = cap,
            // Tightens as the transition builds, so the swirl visibly winds up.
            .swirl = @floatCast(0.85 + 0.75 * intensity),
            // Which way this leans is what reads as the portal swallowing the world (descent)
            // or opening it back up (ascent)!
            .outward_ratio = if (isDescending()) DESCENT_OUTWARD_RATIO else ASCENT_OUTWARD_RATIO,
            .arms = INTAKE_ARMS,
            .arm_phase = @as(f32, @floatFromInt(memory.game.portal_frame)) * INTAKE_ARM_SPIN,
            .arm_spread = INTAKE_ARM_SPREAD,
        });
    }
}

/// Advances the running transition by one logical frame. Called once per tick iteration from `handleTick()`.
pub fn tick() void {
    if (!isActive()) return;

    const g = &memory.game;
    if (isReturning()) {
        tickReturn();
    } else {
        ensureReady();
        g.portal_frame +|= 1;

        if (g.portal_frame >= TOTAL_FRAMES) {
            finish();
            return;
        }

        fillPreview(chunksPerFrame());
        spawnIntake();
    }

    // Both a transition and a return pull the player in over the same PULL_FRAMES,
    // so the moment they are taken is punctuated the same way either way.
    if (isActive() and ready and g.portal_frame == PULL_FRAMES) spawnSwallow();

    // The world is frozen, so pinning the previous-frame values keeps render interpolation from drifting with nothing moving.
    // The transition's own motion is an override.
    g.camera_scale_change = 1.0;
    g.last_camera_pos = g.camera_pos;
    g.last_player_pos = g.player_pos;
}

/// Advances the return fade, committing the retrace on the frame the screen is fully dark.
///
/// Keyed to the exact midpoint frame rather than a range,
/// so resuming a save taken after it cannot commit a second time (bad).
fn tickReturn() void {
    const g = &memory.game;
    ensureReady();
    g.portal_frame +|= 1;

    if (g.portal_frame < RETURN_DIVE_FRAMES) {
        // Budget the D+1 generation across the dive, exactly as a descent budgets its preview, rather
        // than regenerating the whole SimBuffer in the one frame the return commits on.
        fillPreview(chunksPerFrame());
        spawnReturnIntake();
    } else if (g.portal_frame == RETURN_DIVE_FRAMES) {
        commitReturn();
    }

    if (g.portal_frame >= RETURN_FRAMES) {
        g.portal_phase = @intFromEnum(Phase.idle);
        g.portal_frame = 0;
        releasePreview();
        dw.mining.selected_hp = 255;
        dw.mouse.mouse_chunk_coord = null;
    }
}

/// Commits a return under the dark frame: finishes any preview still owed, installs D+1 and adopts the generated chunks,
/// so the arrival fades in on a ready world rather than one being generated.
fn commitReturn() void {
    // Anything the dive did not reach (a stall, a low frame rate) is finished now.
    // Bounded by the preview size, and the screen is already black, so a small catch-up here isn't invisible.
    fillPreview(@intCast(preview.len));

    world.commitRetrace(transition);
    world.SimBuffer.refreshAdopting(memory.game.getPlayerCoord(), PreviewSource{});
    // A return lands on the portal block, which the player may have built over since.
    if (dw.player.escapeSolid()) dw.player.startSoftlockFade();

    // The rubble was sampled from the depth just left; none of it belongs to where we landed.
    clearDebris();
}

/// Emits a return's intake particles: the same inward ring a descent uses, ramped over the dive.
fn spawnReturnIntake() void {
    @setFloatMode(.optimized);
    const t = returnDiveProgress();
    const intensity = smoothstep(t);

    // Held in world scale so the ring hugs the portal as the view dives, but capped at ZOOM_FACTOR:
    const zoom: f32 = @floatCast(memory.game.camera_scale * @min(zoomFactor(), @as(f64, dw.ZOOM_FACTOR)));
    const count: usize = @intFromFloat(4.0 + 34.0 * intensity);

    const cap: u16 = @intFromFloat(@round(22.0 - 12.0 * t));
    if (cap <= 2) return;

    dw.particles.spawnOrbitRing(effectOrigin(), effectColors(), .{
        .count = count,
        .radius_min = INTAKE_RADIUS_MIN * zoom,
        .radius_max = INTAKE_RADIUS_MAX * zoom,
        .size_min = INTAKE_SIZE_MIN * @sqrt(zoom),
        .size_max = INTAKE_SIZE_MAX * @sqrt(zoom),
        .travel_min = @min(cap, 8),
        .travel_max = cap,
        .swirl = @floatCast(0.85 + 0.75 * intensity),
        .outward_ratio = DESCENT_OUTWARD_RATIO,
        .arms = INTAKE_ARMS,
        .arm_phase = @as(f32, @floatFromInt(memory.game.portal_frame)) * INTAKE_ARM_SPIN,
        .arm_spread = INTAKE_ARM_SPREAD,
    });
}

/// Finishes the active depth transition, adopting its generated preview as the new live window.
/// Adapts the preview buffer to the one-method interface `SimBuffer.refreshAdopting()` asks for.
const PreviewSource = struct {
    pub fn get(_: @This(), coord: Coordinate) ?*const Chunk {
        return previewChunk(coord);
    }
};

fn finish() void {
    const g = &memory.game;
    ensureReady();

    const ascended = !isDescending();

    if (ascended) {
        // Records the retrace step and rolls the deeper depth's edits up into markers, then commits.
        // A later return lands ON the portal that was used, not where the player happened to stand.
        world.applyAscent(transition, portalCoord(), ascend_origin);
    } else {
        // Always a fresh descent: going back down from above the frontier is the return fade
        // (triggerReturn()), never this zoom, so the ascent stack is untouched here.
        std.debug.assert(!world.canRetrace());
        // The preview left the ancestor cache holding this depth's parents, already tiered for it.
        world.commitLayer(transition, true);
    }

    // Hand the generated chunks to the SimBuffer so we don't instantly regenerate 256 chunks.
    world.SimBuffer.refreshAdopting(g.getPlayerCoord(), PreviewSource{});

    // The SimBuffer holds the new depth now, so a landing inside rock can be resolved.
    if (dw.player.escapeSolid()) dw.player.startSoftlockFade();

    g.portal_phase = @intFromEnum(Phase.idle);
    g.portal_frame = 0;
    releasePreview();

    // The zoom multiplier drops back to 1 when the transition is over;
    // the newly committed layer is now shown at its normal scale.
    g.camera_scale_change = 1.0;
    dw.mining.selected_hp = 255;
    dw.mouse.mouse_chunk_coord = null;
}

/// Drops the preview buffer and forgets the derived state.
fn releasePreview() void {
    freeBuffers();
    clearDebris();
    preview_w = 0;
    preview_h = 0;
    filled = 0;
    ready = false;
}

/// Rebuilds everything from a save (non-incremental)
/// then brings the preview fully up to date in one go.
/// Called after a load; the frame counter alone decides what the player sees next.
///
/// A return saved AFTER its commit has no preview to rebuild (`ensureReady()` no-ops there):
/// the world is already at D+1 and only the fade-in remains.
pub fn restore() void {
    ready = false;
    if (!isActive()) {
        releasePreview();
        return;
    }
    ensureReady();
    // preview can build at once here as we're doing load and it's okay if that logically takes a while
    if (preview.len != 0) fillPreview(@intCast(preview.len));
}

/// Abandons any running descent and releases its memory. Used when a world is torn down.
pub fn reset() void {
    const g = &memory.game;
    g.portal_phase = @intFromEnum(Phase.idle);
    g.portal_frame = 0;
    releasePreview();
}
